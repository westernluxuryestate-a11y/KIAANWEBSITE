// Flatten all nodes into an array with path/breadcrumbs
export function getFlatLocationHierarchy(): (LocationHierarchyNode & { breadcrumb: string })[] {
  const result: (LocationHierarchyNode & { breadcrumb: string })[] = [];

  function traverse(node: LocationHierarchyNode, currentPath: string[]) {
    const path = [...currentPath, node.name];
    result.push({
      ...node,
      breadcrumb: path.join(' › '),
    });

    if (node.children && node.children.length > 0) {
      for (const child of node.children) {
        traverse(child, path);
      }
    }
  }

  traverse(PUNE_LOCATION_HIERARCHY_TREE, []);
  return result;
}

// Get all Zones under Pune
export function getPuneZones(): LocationHierarchyNode[] {
  return PUNE_LOCATION_HIERARCHY_TREE.children || [];
}

// Get all localities within a given zone ID
export function getLocalitiesByZone(zoneId: PuneZoneId): LocationHierarchyNode[] {
  const zone = (PUNE_LOCATION_HIERARCHY_TREE.children || []).find((z) => z.zoneId === zoneId);
  return zone?.children || [];
}

// Find node by slug or id
export function findHierarchyNode(idOrSlug: string): LocationHierarchyNode | null {
  const target = idOrSlug.toLowerCase().trim();
  let found: LocationHierarchyNode | null = null;

  function traverse(node: LocationHierarchyNode) {
    if (found) return;
    if (node.id.toLowerCase() === target || node.slug.toLowerCase() === target) {
      found = node;
      return;
    }
    if (node.children) {
      for (const child of node.children) {
        traverse(child);
      }
    }
  }

  traverse(PUNE_LOCATION_HIERARCHY_TREE);
  return found;
}

// Search hierarchy by text (matches name, sub-localities, roads, pincode)
export function searchLocationHierarchy(query: string): (LocationHierarchyNode & { breadcrumb: string })[] {
  const clean = query.toLowerCase().trim();
  if (!clean) return [];

  const flat = getFlatLocationHierarchy();
  return flat.filter(
    (item) =>
      item.name.toLowerCase().includes(clean) ||
      (item.pincode && item.pincode.includes(clean)) ||
      (item.zoneName && item.zoneName.toLowerCase().includes(clean)) ||
      (item.description && item.description.toLowerCase().includes(clean))
  );
}
